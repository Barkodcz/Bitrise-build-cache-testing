#!/usr/bin/env python3
"""Flatten bitrise.modular.yml (+ its `include:` tree under .bitrise/**) into a flat bitrise.yml
(spec §4.4) that works on every Bitrise plan, not just Enterprise (modular `include:` is an
Enterprise-plan feature, spec §14-Q11).

Delegates to the official `bitrise yml merge` CLI command (spec §0's "use official steps where
possible") instead of re-implementing Bitrise's merge semantics by hand — this guarantees the output
matches what the real Bitrise platform would resolve. Requires the `bitrise` CLI on PATH.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MODULAR_PATH = os.path.join(ROOT, "bitrise.modular.yml")
OUT_PATH = os.path.join(ROOT, "bitrise.yml")

HEADER = (
    "# GENERATED by tools/yaml/flatten.py (via `bitrise yml merge`) from bitrise.modular.yml + "
    ".bitrise/** —\n"
    "# do not hand-edit. Edit bitrise.modular.yml / .bitrise/00-app.yml / .bitrise/bundles/* /\n"
    "# scenarios/catalog.yml instead, then run `make generate`.\n"
)


def main():
    if not os.path.exists(MODULAR_PATH):
        print(f"flatten: {MODULAR_PATH} not found", file=sys.stderr)
        sys.exit(1)

    result = subprocess.run(
        ["bitrise", "yml", "merge", MODULAR_PATH],
        cwd=ROOT, capture_output=True, text=True,
    )
    if result.returncode != 0:
        print("flatten: `bitrise yml merge` failed:", file=sys.stderr)
        print(result.stdout, file=sys.stderr)
        print(result.stderr, file=sys.stderr)
        sys.exit(result.returncode)

    # `bitrise yml merge <path>` (no --output) prints "config tree:\n{...}\nmerged config:\n<yaml>"
    # to stdout; extract just the merged YAML body.
    marker = "merged config:\n"
    idx = result.stdout.find(marker)
    if idx == -1:
        print("flatten: could not find 'merged config:' marker in `bitrise yml merge` output", file=sys.stderr)
        print(result.stdout, file=sys.stderr)
        sys.exit(1)
    merged_yaml = result.stdout[idx + len(marker):]
    # Strip a single leading/trailing blank-line artifact if present, keep content byte-stable otherwise.
    merged_yaml = re.sub(r"\n+$", "\n", merged_yaml)

    with open(OUT_PATH, "w") as f:
        f.write(HEADER)
        f.write(merged_yaml)
    print(f"flatten: wrote {OUT_PATH} (via bitrise yml merge)")


if __name__ == "__main__":
    main()
