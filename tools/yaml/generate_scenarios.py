#!/usr/bin/env python3
"""Generate .bitrise/workflows/*.yml and .bitrise/pipelines/*.yml from scenarios/catalog.yml
(spec §4.4, §7.4, §7.5). Only `status: implemented` scenarios get real workflows; `planned` ones
are skipped (their catalog entry + doc stub are enough for now, see CLAUDE.md "Scope status").

Run via `make generate` (which also runs tools/yaml/flatten.py afterwards). Re-running this script
must be idempotent and must not require network access or a running Gradle/npm.
"""
import os
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CATALOG_PATH = os.path.join(ROOT, "scenarios", "catalog.yml")
WORKFLOWS_DIR = os.path.join(ROOT, ".bitrise", "workflows")
PIPELINES_DIR = os.path.join(ROOT, ".bitrise", "pipelines")

HEADER = (
    "# GENERATED by tools/yaml/generate_scenarios.py — edit scenarios/catalog.yml or\n"
    "# .bitrise/bundles/* instead. Do not hand-edit this file.\n"
)

VERDICT_EMOJI = {"good": "✅", "bad": "❌", "regression-guard": "\U0001f6e1️"}


def load_catalog():
    with open(CATALOG_PATH) as f:
        return yaml.safe_load(f)


def summary_for(scn):
    emoji = VERDICT_EMOJI.get(scn["verdict"], "❓")
    text = scn.get("symptom") or scn["title"]
    return f"{emoji} {scn['verdict'].upper()} — {text}"


def base_envs(scn, phase):
    return [
        {"SHOWCASE_SCENARIO_ID": scn["id"]},
        {"SHOWCASE_PHASE": phase},
        {"SHOWCASE_STACK": scn["stack"]},
    ]


def extra_envs_from_overrides(overrides, consumed_keys):
    """Any bundle_overrides key not consumed directly as a bundle input becomes a workflow env
    SHOWCASE_<KEY_UPPER>, so project build scripts (e.g. the Android convention plugin) can read it."""
    envs = []
    for k, v in overrides.items():
        if k in consumed_keys:
            continue
        envs.append({f"SHOWCASE_{k.upper()}": str(v)})
    return envs


# ───────────────────────────── Android ─────────────────────────────

def android_steps(scn, phase):
    overrides = dict(scn.get(phase, {}).get("bundle_overrides", {}))
    gradle_bc_enabled = overrides.pop("gradle_bc_enabled", "true") != "false"
    gradle_bc_position = overrides.pop("gradle_bc_position", "before")
    push = overrides.pop("push", "true")
    gradle_options = overrides.pop("gradle_options", "--console=plain")
    change_kind = overrides.pop("change_kind", None)
    consumed = {"gradle_bc_enabled", "gradle_bc_position", "push", "gradle_options", "change_kind"}
    extra_envs = extra_envs_from_overrides(overrides, consumed)

    steps = [{"bundle::setup_checkout": {}}, {"bundle::setup_showcase": {}}]

    bc_step = {"bundle::gradle_build_cache": {"inputs": [{"push": push}, {"verbose": "false"}]}}

    if phase == "measure":
        if change_kind:
            steps.append({"bundle::simulate_change": {"inputs": [{"kind": change_kind}]}})
        else:
            steps.append({"bundle::simulate_change": {}})

    if gradle_bc_enabled and gradle_bc_position != "after":
        steps.append(bc_step)

    steps.append({"bundle::gradle_deps_cache_restore": {}})
    steps.append({"bundle::gradle_build": {"inputs": [{"options": gradle_options}]}})

    if gradle_bc_enabled and gradle_bc_position == "after":
        steps.append(bc_step)

    steps.append({"bundle::gradle_deps_cache_save": {}})
    steps.append({"bundle::collect_metrics": {}})
    steps.append({"bundle::deploy_metrics": {}})
    return steps, extra_envs


# ───────────────────────────── Node ─────────────────────────────

def _npm_key(file_name, ns_scoped=True):
    ns = '{{ getenv "SHOWCASE_NS" }}-' if ns_scoped else ""
    return f'npm-{ns}{{{{ checksum "projects/node/{file_name}" }}}}'


def node_steps(scn, phase):
    overrides = dict(scn.get(phase, {}).get("bundle_overrides", {}))
    restore_key_file = overrides.pop("restore_key_file", "package-lock.json")
    save_key_file = overrides.pop("save_key_file", "package-lock.json")
    key_template = overrides.pop("key_template", None)
    is_key_unique = overrides.pop("is_key_unique", "true")
    save_before_install = overrides.pop("save_before_install", "false") == "true"
    change_kind = overrides.pop("change_kind", None)
    consumed = {"restore_key_file", "save_key_file", "key_template", "is_key_unique",
                "save_before_install", "change_kind"}
    extra_envs = extra_envs_from_overrides(overrides, consumed)

    ns_scoped = key_template is None
    restore_key = key_template or _npm_key(restore_key_file, ns_scoped)
    save_key = key_template or _npm_key(save_key_file, ns_scoped)

    restore_step = {
        "bundle::kb_restore": {"inputs": [{"key": restore_key}, {"name": "npm"}]},
    }
    save_step = {
        "bundle::kb_save": {
            "inputs": [{"key": save_key}, {"paths": "~/.npm"}, {"is_key_unique": is_key_unique}, {"name": "npm"}],
        }
    }

    steps = [{"bundle::setup_checkout": {}}, {"bundle::setup_showcase": {}}]
    if phase == "measure":
        if change_kind:
            steps.append({"bundle::simulate_change": {"inputs": [{"kind": change_kind}]}})
        else:
            steps.append({"bundle::simulate_change": {}})

    if save_before_install:
        steps += [restore_step, save_step, {"bundle::node_install": {}}]
    else:
        steps += [restore_step, {"bundle::node_install": {}}, save_step]

    steps += [{"bundle::collect_metrics": {}}, {"bundle::deploy_metrics": {}}]
    return steps, extra_envs


def _go_key(cache_name):
    return f'{cache_name}-{{{{ getenv "SHOWCASE_NS" }}}}-{{{{ .OS }}}}-{{{{ checksum "projects/go/go.sum" }}}}'


def go_steps(scn, phase):
    overrides = dict(scn.get(phase, {}).get("bundle_overrides", {}))
    go_version = overrides.pop("go_version", "1.22.0")
    cache_build = overrides.pop("cache_build", "true") == "true"
    change_kind = overrides.pop("change_kind", None)
    consumed = {"go_version", "cache_build", "change_kind"}
    extra_envs = extra_envs_from_overrides(overrides, consumed)

    mod_restore = {"bundle::kb_restore": {"inputs": [{"key": _go_key("gomod")}, {"name": "gomod"}]}}
    mod_save = {"bundle::kb_save": {"inputs": [{"key": _go_key("gomod")}, {"paths": "~/go/pkg/mod"}, {"name": "gomod"}]}}
    build_restore = {"bundle::kb_restore": {"inputs": [{"key": _go_key("gobuild")}, {"name": "gobuild"}]}}
    build_save = {"bundle::kb_save": {"inputs": [{"key": _go_key("gobuild")}, {"paths": "~/.cache/go-build"}, {"name": "gobuild"}]}}

    steps = [{"bundle::setup_checkout": {}}, {"bundle::setup_showcase": {}}]
    if phase == "measure":
        if change_kind:
            steps.append({"bundle::simulate_change": {"inputs": [{"kind": change_kind}]}})
        else:
            steps.append({"bundle::simulate_change": {}})

    steps.append(mod_restore)
    if cache_build:
        steps.append(build_restore)
    steps.append({"bundle::go_build": {"inputs": [{"go_version": go_version}]}})
    steps.append(mod_save)
    if cache_build:
        steps.append(build_save)

    steps += [{"bundle::collect_metrics": {}}, {"bundle::deploy_metrics": {}}]
    return steps, extra_envs


def _rust_key(cache_name, include_toolchain_profile, toolchain, profile):
    suffix = f'-{toolchain}-{profile}' if include_toolchain_profile else ''
    return f'{cache_name}-{{{{ getenv "SHOWCASE_NS" }}}}-{{{{ .OS }}}}{suffix}-{{{{ checksum "projects/rust/Cargo.lock" }}}}'


def rust_steps(scn, phase):
    overrides = dict(scn.get(phase, {}).get("bundle_overrides", {}))
    toolchain = overrides.pop("toolchain", "1.82.0")
    profile = overrides.pop("profile", "release")
    target_key_mode = overrides.pop("target_key_mode", "full")
    change_kind = overrides.pop("change_kind", None)
    consumed = {"toolchain", "profile", "target_key_mode", "change_kind"}
    extra_envs = extra_envs_from_overrides(overrides, consumed)

    include = target_key_mode == "full"
    registry_key = _rust_key("cargo-registry", False, toolchain, profile)  # registry is never profile/toolchain-scoped
    target_key = _rust_key("cargo-target", include, toolchain, profile)

    registry_restore = {"bundle::kb_restore": {"inputs": [{"key": registry_key}, {"name": "cargo-registry"}]}}
    registry_save = {"bundle::kb_save": {"inputs": [{"key": registry_key}, {"paths": "~/.cargo/registry\n~/.cargo/git"}, {"name": "cargo-registry"}]}}
    target_restore = {"bundle::kb_restore": {"inputs": [{"key": target_key}, {"name": "cargo-target"}]}}
    target_save = {"bundle::kb_save": {"inputs": [{"key": target_key}, {"paths": "projects/rust/target"}, {"name": "cargo-target"}]}}

    steps = [{"bundle::setup_checkout": {}}, {"bundle::setup_showcase": {}}]
    if phase == "measure":
        if change_kind:
            steps.append({"bundle::simulate_change": {"inputs": [{"kind": change_kind}]}})
        else:
            steps.append({"bundle::simulate_change": {}})

    steps += [
        registry_restore, target_restore,
        {"bundle::rust_build": {"inputs": [{"toolchain": toolchain}, {"profile": profile}]}},
        registry_save, target_save,
        {"bundle::collect_metrics": {}}, {"bundle::deploy_metrics": {}},
    ]
    return steps, extra_envs


def _py_key(key_file):
    return f'{{{{ getenv "SHOWCASE_NS" }}}}-{{{{ .OS }}}}-{{{{ checksum "{key_file}" }}}}'


def python_steps(scn, phase):
    overrides = dict(scn.get(phase, {}).get("bundle_overrides", {}))
    app = overrides.pop("app", "pip")
    cache_name = overrides.pop("cache_name", "pip-cache")
    cache_paths = overrides.pop("cache_paths", "~/.cache/pip")
    restore_key_file = overrides.pop("restore_key_file", "projects/python/pip_app/requirements.txt")
    save_key_file = overrides.pop("save_key_file", restore_key_file)
    change_kind = overrides.pop("change_kind", None)
    consumed = {"app", "cache_name", "cache_paths", "restore_key_file", "save_key_file", "change_kind"}
    extra_envs = extra_envs_from_overrides(overrides, consumed)

    restore_key = f'{cache_name}-{_py_key(restore_key_file)}'
    save_key = f'{cache_name}-{_py_key(save_key_file)}'

    steps = [{"bundle::setup_checkout": {}}, {"bundle::setup_showcase": {}}]
    if phase == "measure":
        if change_kind:
            steps.append({"bundle::simulate_change": {"inputs": [{"kind": change_kind}]}})
        else:
            steps.append({"bundle::simulate_change": {}})

    steps += [
        {"bundle::kb_restore": {"inputs": [{"key": restore_key}, {"name": cache_name}]}},
        {"bundle::python_install": {"inputs": [{"app": app}]}},
        {"bundle::kb_save": {"inputs": [{"key": save_key}, {"paths": cache_paths}, {"name": cache_name}]}},
        {"bundle::collect_metrics": {}}, {"bundle::deploy_metrics": {}},
    ]
    return steps, extra_envs


def _mvn_key(glob):
    return f'{{{{ getenv "SHOWCASE_NS" }}}}-{{{{ .OS }}}}-{{{{ checksum "{glob}" }}}}'


def maven_steps(scn, phase):
    overrides = dict(scn.get(phase, {}).get("bundle_overrides", {}))
    key_glob = overrides.pop("key_glob", "projects/maven/**/pom.xml")
    cache_target_dirs = overrides.pop("cache_target_dirs", "false") == "true"
    change_kind = overrides.pop("change_kind", None)
    consumed = {"key_glob", "cache_target_dirs", "change_kind"}
    extra_envs = extra_envs_from_overrides(overrides, consumed)

    key = f'm2-{_mvn_key(key_glob)}'
    paths = "~/.m2/repository"
    if cache_target_dirs:
        paths += "\nprojects/maven/core/target\nprojects/maven/leaf/target"

    steps = [{"bundle::setup_checkout": {}}, {"bundle::setup_showcase": {}}]
    if phase == "measure":
        if change_kind:
            steps.append({"bundle::simulate_change": {"inputs": [{"kind": change_kind}]}})
        else:
            steps.append({"bundle::simulate_change": {}})

    steps += [
        {"bundle::kb_restore": {"inputs": [{"key": key}, {"name": "m2-repo"}]}},
        {"bundle::maven_build": {}},
        {"bundle::kb_save": {"inputs": [{"key": key}, {"paths": paths}, {"name": "m2-repo"}]}},
        {"bundle::collect_metrics": {}}, {"bundle::deploy_metrics": {}},
    ]
    return steps, extra_envs


STACK_BUILDERS = {
    "android": android_steps,
    "node": node_steps,
    "go": go_steps,
    "rust": rust_steps,
    "python": python_steps,
    "jvm-maven": maven_steps,
}


def build_workflow(scn, phase, stacks_cfg):
    builder = STACK_BUILDERS[scn["stack"]]
    steps, extra_envs = builder(scn, phase)

    logical_stack = scn.get("stack_id", "linux-default")
    stack_entry = stacks_cfg["stacks"].get(logical_stack, stacks_cfg["stacks"]["linux-default"])

    wf = {
        "title": f"{scn['id']} · {phase}",
        "summary": summary_for(scn),
        "meta": {"bitrise.io": {"stack": stack_entry["stack"]}},
        "envs": base_envs(scn, phase) + extra_envs,
        "steps": steps,
    }
    return wf


def main():
    catalog = load_catalog()
    with open(os.path.join(ROOT, "tools", "yaml", "stacks.yml")) as f:
        stacks_cfg = yaml.safe_load(f)

    by_stack = {}
    for scn in catalog["scenarios"]:
        if scn.get("status") != "implemented":
            continue
        by_stack.setdefault(scn["stack"], []).append(scn)

    os.makedirs(WORKFLOWS_DIR, exist_ok=True)
    os.makedirs(PIPELINES_DIR, exist_ok=True)

    for stack, scns in sorted(by_stack.items()):
        workflows = {}
        pipeline_workflows = {}
        measure_ids = []

        for scn in scns:
            sid = scn["id"].lower()
            seed_name = f"{sid}__1_seed"
            measure_name = f"{sid}__2_measure"

            workflows[seed_name] = build_workflow(scn, "seed", stacks_cfg)
            workflows[measure_name] = build_workflow(scn, "measure", stacks_cfg)

            pipeline_workflows[seed_name] = {}
            pipeline_workflows[measure_name] = {"depends_on": [seed_name]}
            measure_ids.append(measure_name)

        # NOTE: spec §7.1 suggested a leading-underscore "utility workflow" name (`_report_<stack>`)
        # for workflows never triggered directly. `bitrise yml validate` rejects that: a workflow
        # whose name starts with `_` is a reserved "utility workflow" and the platform refuses to let
        # pipelines reference one at all (verified 2026-11-26, see docs/reference/verified-facts.md).
        # Using a plain name instead; it's still clearly a reporting-only workflow by name and title.
        report_wf_name = f"report_{stack}"
        workflows[report_wf_name] = {
            "title": f"Report · showcase-{stack}",
            "summary": "Renders the HTML/Markdown report and runs assertions for this stack.",
            "envs": [{"SHOWCASE_STACK": stack}],
            # bundle::setup_checkout is required here too: tools/report/render.py and
            # tools/report/assertions.py live in this repo, and this workflow otherwise never clones
            # it (verified 2026-11-26: without this, the report scripts fail with "No such file or
            # directory" because $BITRISE_SOURCE_DIR is empty — see docs/reference/verified-facts.md).
            "steps": [{"bundle::setup_checkout": {}}, {"bundle::report": {}}],
        }
        pipeline_workflows[report_wf_name] = {
            "depends_on": measure_ids,
            "should_always_run": "workflow",
        }

        wf_doc = {"workflows": workflows}
        wf_path = os.path.join(WORKFLOWS_DIR, f"{stack}.yml")
        with open(wf_path, "w") as f:
            f.write(HEADER)
            yaml.dump(wf_doc, f, sort_keys=False, default_flow_style=False, width=4096, allow_unicode=True)

        pipeline_doc = {"pipelines": {f"showcase-{stack}": {"workflows": pipeline_workflows}}}
        pl_path = os.path.join(PIPELINES_DIR, f"{stack}.yml")
        with open(pl_path, "w") as f:
            f.write(HEADER)
            yaml.dump(pipeline_doc, f, sort_keys=False, default_flow_style=False, width=4096, allow_unicode=True)

        print(f"generate_scenarios: wrote {wf_path} ({len(scns)} scenarios) and {pl_path}")


if __name__ == "__main__":
    main()
