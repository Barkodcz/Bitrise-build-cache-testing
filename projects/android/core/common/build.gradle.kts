plugins {
    kotlin("jvm")
    `java-library`
}

repositories {
    mavenCentral()
}

dependencies {
    testImplementation(platform("org.junit:junit-bom:5.10.3"))
    testImplementation("org.junit.jupiter:junit-jupiter")
}

tasks.test {
    useJUnitPlatform()
}

// --- Showcase hook (AND-B03 / AND-G01) -------------------------------------------------
// When SHOWCASE_VOLATILE_BUILDCONFIG=true, generate a Kotlin source file whose content bakes
// in System.currentTimeMillis() as a compile-time constant. This simulates the real Android
// `buildConfigField` anti-pattern where a volatile value changes on every build, forcing a
// build-cache miss on every run (AND-B03). When unset/false, the constant is fixed (0L) so the
// module's compile inputs are stable and remote-cache hits are possible across builds (AND-G01).
val generatedSrcDir = layout.buildDirectory.dir("generated/showcase/kotlin")

val generateShowcaseBuildConfig by tasks.registering {
    val outputDir = generatedSrcDir
    val volatile = (System.getenv("SHOWCASE_VOLATILE_BUILDCONFIG") ?: "false").equals("true", ignoreCase = true)

    outputs.dir(outputDir)
    // Track the toggle itself as an input so flipping it always invalidates this task,
    // even across an otherwise-identical build.
    inputs.property("volatileBuildConfig", volatile)
    // When volatile, this task must never be considered up-to-date / cacheable, since its
    // "output" (a wall-clock timestamp) is different on every single execution.
    if (volatile) {
        outputs.upToDateWhen { false }
        outputs.cacheIf { false }
    }

    doLast {
        val buildTime: Long = if (volatile) System.currentTimeMillis() else 0L
        val dir = outputDir.get().asFile.resolve("com/showcase/core/common")
        dir.mkdirs()
        dir.resolve("ShowcaseBuildConfig.kt").writeText(
            """
            package com.showcase.core.common

            // Auto-generated by the :core:common `generateShowcaseBuildConfig` task.
            // SHOWCASE_VOLATILE_BUILDCONFIG=$volatile at generation time.
            object ShowcaseBuildConfig {
                const val BUILD_TIME: Long = ${buildTime}L
            }

            """.trimIndent()
        )
    }
}

kotlin {
    sourceSets.main {
        kotlin.srcDir(generatedSrcDir)
    }
}

tasks.named("compileKotlin") {
    dependsOn(generateShowcaseBuildConfig)
}
